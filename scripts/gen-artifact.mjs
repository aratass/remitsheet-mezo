// Reads the Foundry build output and writes:
//   web/src/generated/remitsheet.ts              ABI, init code, runtime code hash, CREATE2 address
//   contracts/verify/Remitsheet.standard-input.json  solc standard JSON input for explorer verification
// and, when a native solc 0.8.30 binary is available (SOLC env var or ~/.svm), checks that the
// standard JSON input reproduces exactly the bytecode Foundry produced.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { homedir } from "node:os";
import { getContractAddress, keccak256, stringToHex } from "viem";

const root = new URL("..", import.meta.url).pathname;
const artifact = JSON.parse(readFileSync(`${root}contracts/out/Remitsheet.sol/Remitsheet.json`, "utf8"));
const source = readFileSync(`${root}contracts/src/Remitsheet.sol`, "utf8");

const initCode = artifact.bytecode.object;
const runtimeCode = artifact.deployedBytecode.object;
// Arachnid's deterministic deployment proxy; it exists on Mezo testnet and mainnet (checked with eth_getCode), and Anvil predeploys it.
const factory = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const salt = stringToHex("Remitsheet v2", { size: 32 });
const address = getContractAddress({ opcode: "CREATE2", from: factory, salt, bytecode: initCode });

const settings = {
  optimizer: { enabled: true, runs: 20000 },
  evmVersion: "cancun",
  metadata: { bytecodeHash: "none", appendCBOR: false },
  outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
};
const standardInput = {
  language: "Solidity",
  sources: { "contracts/src/Remitsheet.sol": { content: source } },
  settings,
};
mkdirSync(`${root}contracts/verify`, { recursive: true });
writeFileSync(`${root}contracts/verify/Remitsheet.standard-input.json`, JSON.stringify(standardInput, null, 2) + "\n");

const solc = process.env.SOLC || `${homedir()}/.svm/0.8.30/solc-0.8.30`;
if (existsSync(solc)) {
  const out = JSON.parse(execFileSync(solc, ["--standard-json"], { input: JSON.stringify(standardInput) }).toString());
  const errors = (out.errors || []).filter((e) => e.severity === "error");
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  const c = out.contracts["contracts/src/Remitsheet.sol"].Remitsheet;
  if ("0x" + c.evm.bytecode.object !== initCode) throw new Error("standard JSON input does not reproduce the Foundry init code");
  console.log("solc standard JSON input reproduces the Foundry bytecode exactly");
} else {
  console.log(`solc not found at ${solc}; skipped the reproducibility check`);
}

const abi = artifact.abi;
const ts = `// Generated by scripts/gen-artifact.mjs from the Foundry build. Do not edit by hand.
export const REMITSHEET_ABI = ${JSON.stringify(abi, null, 2)} as const;

/** Contract creation code (solc 0.8.30, optimizer 20000 runs, evm cancun, no metadata hash). */
export const REMITSHEET_INIT_CODE = "${initCode}" as const;

/** keccak256 of the deployed runtime code, used to recognise genuine Remitsheet deployments. */
export const REMITSHEET_RUNTIME_HASH = "${keccak256(runtimeCode)}" as const;

/** Arachnid deterministic deployment proxy (CREATE2 factory). */
export const CREATE2_FACTORY = "${factory}" as const;

/** CREATE2 salt: "Remitsheet v2" as bytes32. */
export const CREATE2_SALT = "${salt}" as const;

/** Address Remitsheet gets on every chain where it is deployed through the factory. */
export const REMITSHEET_ADDRESS = "${address}" as const;
`;
mkdirSync(`${root}web/src/generated`, { recursive: true });
writeFileSync(`${root}web/src/generated/remitsheet.ts`, ts);
writeFileSync(
  `${root}contracts/deployment.json`,
  JSON.stringify(
    {
      contract: "Remitsheet",
      compiler: "solc 0.8.30",
      settings: { optimizerRuns: 20000, evmVersion: "cancun", bytecodeHash: "none", appendCBOR: false },
      create2Factory: factory,
      salt,
      initCodeHash: keccak256(initCode),
      runtimeCodeHash: keccak256(runtimeCode),
      address,
    },
    null,
    2,
  ) + "\n",
);
console.log(`init code ${(initCode.length - 2) / 2} bytes, runtime ${(runtimeCode.length - 2) / 2} bytes`);
console.log(`CREATE2 address: ${address}`);
